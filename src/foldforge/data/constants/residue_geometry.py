#: Every frame, by the name a spec asks for.
FRAMES = {"esmfold2": _LANGUAGE_MODEL_FOLDER}


def as_conformers(name: str) -> dict[str, tuple[list[str], np.ndarray]]:
    """Return {residue: (atom names, positions)} for the named frame."""
    try:
        frame = FRAMES[name]
    except KeyError:
        message = f"unknown residue geometry {name!r}; known: {', '.join(FRAMES)}"
        raise KeyError(message) from None
    return {
        residue: (list(atoms), np.array(list(atoms.values()), np.float32))
        for residue, atoms in frame.items()
    }
